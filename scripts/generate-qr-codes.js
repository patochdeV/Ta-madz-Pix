#!/usr/bin/env node
/**
 * Génère les codes QR pour tous les items Tamagotchi
 * Les codes QR sont convertis en base64 et sauvegardés dans data/embedded-qr-codes.ts
 * Exécution: node scripts/generate-qr-codes.js
 */

const QRCode = require('qrcode');
const fs = require('fs');
const path = require('path');

const OUTPUT_DIR = path.join(__dirname, '..', 'data');
const OUTPUT_FILE = path.join(OUTPUT_DIR, 'embedded-qr-codes.ts');

// Créer le répertoire s'il n'existe pas
if (!fs.existsSync(OUTPUT_DIR)) {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
}

// Importer les items pour générer les codes QR correspondants
const items = require(path.join(__dirname, '..', 'data', 'tamagotchi-items.ts'));

async function generateQRCodes() {
  console.log('🔧 Génération des codes QR...\n');

  const qrCodeData = {};
  let count = 0;
  let errors = 0;

  // Générer un code QR pour chaque item
  for (const item of items.allItems) {
    try {
      // Créer le code à encoder: "tc-categoryCode-itemCode"
      const code = `tc-${item.categoryCode}-${item.itemCode}`;

      // Générer le code QR en tant qu'image PNG
      const qrImage = await QRCode.toDataURL(code, {
        errorCorrectionLevel: 'H',
        type: 'image/png',
        width: 300,
        margin: 2,
        color: {
          dark: '#000000',
          light: '#FFFFFF',
        },
      });

      qrCodeData[item.id] = qrImage;
      count++;

      if (count % 20 === 0) {
        console.log(`  ✓ ${count} codes QR générés...`);
      }
    } catch (error) {
      console.error(`  ✗ Erreur pour l'item ${item.id}: ${error.message}`);
      errors++;
    }
  }

  // Générer le fichier TypeScript
  const content = `/**
 * Embedded QR codes as base64 data URLs.
 * Auto-generated by scripts/generate-qr-codes.js
 * To regenerate after adding new items, run: node scripts/generate-qr-codes.js
 */

export const embeddedQRCodes: Record<string, string> = {
${Object.entries(qrCodeData)
  .map(([id, dataUrl]) => `  '${id}': '${dataUrl}',`)
  .join('\n')}
};

// Export counts for statistics
export const qrCodeStats = {
  total: ${count},
  failed: ${errors},
};
`;

  // Sauvegarder le fichier
  fs.writeFileSync(OUTPUT_FILE, content, 'utf8');

  console.log(`\n✅ Code QR généré avec succès!`);
  console.log(`   📊 ${count} codes QR générés`);
  console.log(`   ⚠️  ${errors} erreurs`);
  console.log(`   📁 Fichier: ${OUTPUT_FILE}`);
}

// Lancer la génération
generateQRCodes().catch((error) => {
  console.error('❌ Erreur fatale:', error);
  process.exit(1);
});
